const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const { version } = require('../package.json');
const architecture = process.env.BLUVIBOARD_MACOS_ARCH;
if (!['arm64', 'x64'].includes(architecture)) throw new Error('Select arm64 or x64');
const target = architecture === 'arm64' ? 'aarch64-apple-darwin' : 'x86_64-apple-darwin';
const root = path.resolve(__dirname, '..');
const bundles = path.join(root, 'src-tauri/target', target, 'release/bundle/dmg');
const candidates = fs.readdirSync(bundles).filter(name => name.endsWith(`_${version}_${architecture === 'arm64' ? 'aarch64' : 'x64'}.dmg`));
if (candidates.length !== 1) throw new Error(`Expected one current DMG: ${candidates}`);
const preview = process.env.BLUVIBOARD_DESKTOP_PREVIEW === 'true';
const name = `BluviBoard-${preview ? 'Offline-Preview-' : ''}${version}-macOS-${architecture}.dmg`;
const bytes = fs.readFileSync(path.join(bundles, candidates[0]));
const output = path.join(root, 'artifacts');
fs.mkdirSync(output, { recursive: true });
fs.writeFileSync(path.join(output, name), bytes);
fs.writeFileSync(path.join(output, `${name}.sha256`), `${createHash('sha256').update(bytes).digest('hex')}  ${name}\n`);
console.log(`Packaged ${name}`);
